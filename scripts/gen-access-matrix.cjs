// Regenerates docs/security/access-control-matrix.md from the code permission catalogue.
// Usage: pnpm --filter @mzn/shared build && node scripts/gen-access-matrix.cjs
const { writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { ALL_PERMISSIONS, DEFAULT_ROLES } = require('../packages/shared/dist/index.js');

const roles = DEFAULT_ROLES;
const header = `| Permission | ${roles.map((r) => r.key).join(' | ')} |`;
const sep = `|---|${roles.map(() => ':-:').join('|')}|`;
const rows = [...ALL_PERMISSIONS]
  .sort()
  .map(
    (p) => `| \`${p}\` | ${roles.map((r) => (r.permissions.includes(p) ? 'Y' : '')).join(' | ')} |`,
  );
const out = [
  '# Access control matrix (default roles)',
  '',
  '> Generated by `node scripts/gen-access-matrix.cjs` from `packages/shared/src/permissions.ts`. Do not edit by hand.',
  '> Roles are editable at runtime by System Admins; this matrix shows the seeded defaults. Scope rules',
  '> (own sections, own organization, own records) and separation-of-duties checks are enforced in services',
  '> in addition to these permissions. "Y" = granted.',
  '',
  `Staff roles (MFA mandatory): ${roles
    .filter((r) => r.isStaff)
    .map((r) => r.key)
    .join(', ')}.`,
  '',
  header,
  sep,
  ...rows,
  '',
].join('\n');
writeFileSync(resolve(__dirname, '../docs/security/access-control-matrix.md'), out);
console.log(`wrote ${rows.length} permissions x ${roles.length} roles`);
